CREATE TABLE IF NOT EXISTS sunat_casos_buzon (
 id_documento BIGINT NOT NULL PRIMARY KEY,id_cliente INT NOT NULL,id_responsable INT NULL,
 responsable VARCHAR(180) NOT NULL,cliente VARCHAR(255) NOT NULL,ruc VARCHAR(11) NOT NULL,asunto VARCHAR(255) NOT NULL,
 prioridad VARCHAR(12) NOT NULL,fecha_limite DATE NULL,observaciones_equipo TEXT NULL,
 estado VARCHAR(12) NOT NULL DEFAULT 'ABIERTO',creado_por INT NOT NULL,modificado_por INT NOT NULL,
 version INT NOT NULL DEFAULT 1,creado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 actualizado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX idx_responsable_estado(id_responsable,estado,fecha_limite),INDEX idx_cliente(id_cliente)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS sunat_casos_accesos (
 id_documento BIGINT NOT NULL,id_usuario INT NOT NULL,PRIMARY KEY(id_documento,id_usuario)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS sunat_casos_historial (
 id_historial BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,id_documento BIGINT NOT NULL,id_actor INT NOT NULL,
 actor VARCHAR(180) NOT NULL,accion VARCHAR(40) NOT NULL,detalle LONGTEXT NOT NULL,
 creado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,INDEX idx_documento(id_documento,id_historial)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS sunat_casos_notas (
 id_nota BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,id_documento BIGINT NOT NULL,id_usuario INT NOT NULL,
 autor VARCHAR(180) NOT NULL,contenido LONGTEXT NOT NULL,clave VARCHAR(80) NOT NULL,
 creado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,UNIQUE KEY uq_nota(id_documento,id_usuario,clave)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS sunat_casos_notificaciones (
 id_notificacion BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,id_usuario INT NOT NULL,id_documento BIGINT NOT NULL,
 titulo VARCHAR(180) NOT NULL,cliente VARCHAR(255) NOT NULL,prioridad VARCHAR(12) NOT NULL,fecha_limite DATE NULL,
 leida TINYINT NOT NULL DEFAULT 0,creado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_avisos_usuario(id_usuario,leida,id_notificacion)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS sunat_casos_correos (
 id_correo BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,id_documento BIGINT NOT NULL,id_usuario INT NOT NULL,
 destinatario VARCHAR(254) NOT NULL,asunto VARCHAR(255) NOT NULL,mensaje TEXT NOT NULL,
 estado VARCHAR(12) NOT NULL DEFAULT 'PENDIENTE',intentos INT NOT NULL DEFAULT 0,
 siguiente_intento DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,ultimo_error VARCHAR(255) NULL,
 actualizado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 creado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,INDEX idx_cola(estado,siguiente_intento)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS sunat_casos_migraciones (clave VARCHAR(80) PRIMARY KEY,aplicado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
