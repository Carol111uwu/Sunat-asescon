    public static function fecha(string $periodo, string $ruc): ?string
    {
        if (!isset(self::CALENDARIO[$periodo]) || !preg_match('/^\d{11}$/D', $ruc)) return null;
        $digito = (int)substr($ruc,-1);
        $indice = $digito < 2 ? $digito : 1 + intdiv($digito,2);
        return self::CALENDARIO[$periodo][$indice] ?? null;
    }

    public static function periodos(): array { return array_keys(self::CALENDARIO); }
}
